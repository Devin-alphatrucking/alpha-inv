-- ---------------------------------------------------------------------------
-- 3. Row-Level Security
--
-- Every request runs with `SET LOCAL app.org_id = '<company>'` (set by the
-- scoped client in apps/web/src/lib/org/scoped-db.ts). A row is visible and
-- writable only when its organizationId equals that setting. With no setting
-- the comparison is NULL, so nothing is visible: it fails closed.
--
-- IMPORTANT: Postgres does not apply these policies to the table OWNER or to
-- superusers / roles with BYPASSRLS. The web app must connect as a separate,
-- ordinary role (see packages/db/prisma/rls-setup/app-role.sql); migrations
-- keep running as the owner. The admin Settings page shows whether isolation
-- is actually active for the connected role.
-- ---------------------------------------------------------------------------
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'Project','Category','Material','Vendor','Invoice','InvoiceLineItem','Payment',
    'ProjectNote','ProjectAssignment','AuditLog','PageUsageEvent'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format($p$CREATE POLICY company_isolation ON %I
      USING ("organizationId" = current_setting('app.org_id', true))
      WITH CHECK ("organizationId" = current_setting('app.org_id', true))$p$, t);
  END LOOP;

  -- Logs may have no company (failed sign-in, unauthenticated errors). Anyone may
  -- append; only the owning company can read, change or delete its own rows.
  FOREACH t IN ARRAY ARRAY['ActivityLog','ApiErrorLog'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format($p$CREATE POLICY log_append ON %I FOR INSERT WITH CHECK (true)$p$, t);
    EXECUTE format($p$CREATE POLICY log_read ON %I FOR SELECT
      USING ("organizationId" = current_setting('app.org_id', true))$p$, t);
    EXECUTE format($p$CREATE POLICY log_change ON %I FOR UPDATE
      USING ("organizationId" = current_setting('app.org_id', true))
      WITH CHECK ("organizationId" = current_setting('app.org_id', true))$p$, t);
    EXECUTE format($p$CREATE POLICY log_delete ON %I FOR DELETE
      USING ("organizationId" = current_setting('app.org_id', true))$p$, t);
  END LOOP;
END $$;
